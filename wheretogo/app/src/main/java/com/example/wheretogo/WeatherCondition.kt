package com.example.wheretogo

/** Open-Meteo WMO weather codes; UNKNOWN keeps future or invalid codes explicit. */
enum class WeatherCondition {
    CLEAR, MAINLY_CLEAR, PARTLY_CLOUDY, OVERCAST, FOG, RIME_FOG,
    LIGHT_DRIZZLE, MODERATE_DRIZZLE, DENSE_DRIZZLE, LIGHT_FREEZING_DRIZZLE, DENSE_FREEZING_DRIZZLE,
    LIGHT_RAIN, MODERATE_RAIN, HEAVY_RAIN, LIGHT_FREEZING_RAIN, HEAVY_FREEZING_RAIN,
    LIGHT_SNOW, MODERATE_SNOW, HEAVY_SNOW, SNOW_GRAINS,
    LIGHT_RAIN_SHOWERS, MODERATE_RAIN_SHOWERS, HEAVY_RAIN_SHOWERS, LIGHT_SNOW_SHOWERS, HEAVY_SNOW_SHOWERS,
    THUNDERSTORM, THUNDERSTORM_LIGHT_HAIL, HEAVY_THUNDERSTORM, THUNDERSTORM_HEAVY_HAIL, UNKNOWN;

    companion object {
        fun fromWmoCode(code: Int): WeatherCondition = when (code) {
            0 -> CLEAR; 1 -> MAINLY_CLEAR; 2 -> PARTLY_CLOUDY; 3 -> OVERCAST
            45 -> FOG; 48 -> RIME_FOG
            51 -> LIGHT_DRIZZLE; 53 -> MODERATE_DRIZZLE; 55 -> DENSE_DRIZZLE
            56 -> LIGHT_FREEZING_DRIZZLE; 57 -> DENSE_FREEZING_DRIZZLE
            61 -> LIGHT_RAIN; 63 -> MODERATE_RAIN; 65 -> HEAVY_RAIN
            66 -> LIGHT_FREEZING_RAIN; 67 -> HEAVY_FREEZING_RAIN
            71 -> LIGHT_SNOW; 73 -> MODERATE_SNOW; 75 -> HEAVY_SNOW; 77 -> SNOW_GRAINS
            80 -> LIGHT_RAIN_SHOWERS; 81 -> MODERATE_RAIN_SHOWERS; 82 -> HEAVY_RAIN_SHOWERS
            85 -> LIGHT_SNOW_SHOWERS; 86 -> HEAVY_SNOW_SHOWERS
            95 -> THUNDERSTORM; 96 -> THUNDERSTORM_LIGHT_HAIL
            97 -> HEAVY_THUNDERSTORM; 99 -> THUNDERSTORM_HEAVY_HAIL
            else -> UNKNOWN
        }
    }
}
